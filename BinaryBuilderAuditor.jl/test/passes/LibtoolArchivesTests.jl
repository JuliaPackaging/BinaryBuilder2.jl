using Test, BinaryBuilderAuditor, BinaryBuilderProducts, Base.BinaryPlatforms
using BinaryBuilderAuditor: remove_libtool_archives!

@testset "remove_libtool_archives!" begin
    alias = "/workspace/destdir/target-x86_64-linux-gnu"
    mktempdir() do prefix
        p(path) = joinpath(prefix, path)
        mkpath(p("lib/plugins"))
        mkpath(p("share/licenses/Foo"))
        touch(p("share/licenses/Foo/LICENSE"))
        la(dir) = "# libfoo.la - a libtool library file\n# Generated by libtool (GNU libtool) 2.4.7\nlibdir='$(alias)/$(dir)'\n"
        write(p("lib/libfoo.la"), la("lib"))
        write(p("lib/plugins/bar.la"), la("lib/plugins"))
        # Symlinks, which sort before their target, absolute ones included
        symlink("libfoo.la", p("lib/a-libfoo.la"))
        symlink("$(alias)/lib/libfoo.la", p("lib/abs-libfoo.la"))
        write(p("lib/libfoo.las"), la("lib"))
        write(p("lib/notes.la"), "Lua source, not a libtool archive\n")
        write(p("lib/empty.la"), "")

        # `readonly` leaves them alone
        @test success(audit!(prefix, AbstractProduct[], AuditInfo(); prefix_alias=alias, readonly=true))
        @test isfile(p("lib/libfoo.la"))

        result = AuditResult(scan_files(prefix, HostPlatform(); prefix_alias=alias))
        @test result.scan.libtool_archives == Set(["lib/a-libfoo.la", "lib/abs-libfoo.la", "lib/libfoo.la", "lib/plugins/bar.la"])
        remove_libtool_archives!(result)
        @test success(result)
        @test sort([r.identifier for r in result.pass_results["remove_libtool_archives!"]]) ==
              ["lib/a-libfoo.la", "lib/abs-libfoo.la", "lib/libfoo.la", "lib/plugins/bar.la"]
        @test !ispath(p("lib/libfoo.la"))
        @test !islink(p("lib/a-libfoo.la"))
        @test !islink(p("lib/abs-libfoo.la"))
        @test !ispath(p("lib/plugins/bar.la"))
        @test isfile(p("lib/libfoo.las"))
        @test isfile(p("lib/notes.la"))
        @test isfile(p("lib/empty.la"))
        @test isempty(result.scan.libtool_archives)
        @test sort(filter(endswith(".la"), collect(keys(result.scan.files)))) == ["lib/empty.la", "lib/notes.la"]
    end
end
